/**
 * Why these are inline SVGs rather than lucide-react components:
 *
 * lucide-react 1.x removed every brand icon — there is no Github, Linkedin,
 * Twitter/X or Medium, and its `X` export is the generic close-cross, not the brand
 * mark. That left `Mail` as the only usable icon, and lucide marks its icon modules
 * 'use client', so importing it pushed a ~1.5 KB client runtime onto a homepage that
 * otherwise ships no route JS at all.
 *
 * So Mail is drawn here on lucide's own geometry (24-unit box, 2px round-capped
 * stroke) to keep that visual language, and the four brand marks are the official
 * glyphs in the same box, filled with currentColor. All of it renders on the server.
 */

